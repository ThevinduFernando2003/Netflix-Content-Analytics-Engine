"""Auto-generate reports/model_leaderboard.md from recorded runs."""

from __future__ import annotations

from collections import defaultdict
from typing import Any

from src.config import AppConfig
from src.tracking.mlflow_utils import load_run_records


def _latest_per_candidate(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Keep one row per candidate when a head has been trained more than once."""
    chosen: dict[str, dict[str, Any]] = {}
    for rec in records:
        key = str(rec.get("candidate", ""))
        prev = chosen.get(key)
        if prev is None or str(rec.get("written_at", "")) >= str(prev.get("written_at", "")):
            chosen[key] = rec
    return list(chosen.values())


def write_leaderboard(cfg: AppConfig) -> dict[str, Any]:
    records = load_run_records(cfg)
    by_head: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for rec in records:
        by_head[rec["head"]].append(rec)
    lines = [
        "# Model leaderboard",
        "",
        "Generated by `src/models/evaluate.py` from recorded training runs. Not hand-written.",
        "",
    ]
    summary: dict[str, Any] = {}
    for head, spec in cfg.models["heads"].items():
        recs = _latest_per_candidate(by_head.get(head, []))
        metric = spec["primary_metric"]
        greater = bool(spec.get("primary_greater_is_better", True))
        lines += [f"## {spec['display_name']} (`{head}`)", "", f"Primary metric: **{metric}**.", ""]
        lines += [
            "| candidate | baseline | primary | other metrics | seconds |",
            "|---|---|---|---|---|",
        ]
        baseline_val = None
        best_val = None
        best_name = None
        for rec in sorted(recs, key=lambda r: r.get("candidate", "")):
            val = (rec.get("metrics") or {}).get(metric)
            others = ", ".join(
                f"{k}={v:.3f}" if isinstance(v, float) else f"{k}={v}"
                for k, v in (rec.get("metrics") or {}).items()
                if k != metric
            )
            lines.append(
                f"| {rec.get('candidate')} | {rec.get('is_baseline')} | {val} | {others} | {rec.get('duration_seconds', '')} |"
            )
            if rec.get("is_baseline") and val is not None:
                baseline_val = float(val)
            if val is not None and not rec.get("is_baseline"):
                if best_val is None or (val > best_val if greater else val < best_val):
                    best_val = float(val)
                    best_name = rec.get("candidate")
        lines.append("")
        summary[head] = {
            "primary": metric,
            "best": best_name,
            "best_value": best_val,
            "baseline": baseline_val,
        }
    path = cfg.path("reports_dir") / "model_leaderboard.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"n_runs": len(records), "heads": summary}
